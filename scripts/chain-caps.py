#!/usr/bin/env python3
"""chain-caps: what each chain-table row can do, measured by running the built CLIs (Linux CI).
  python3 scripts/chain-caps.py [BIN]          print the table (BIN default $BIN, else target/release)
  python3 scripts/chain-caps.py --check [BIN]  fail if docs/CHAINS.md's table differs
Columns (each one an executed probe, never a hand-kept flag):
  derive: `derive --chain C --count 1 --public-only` on the public BIP-39 test phrase
          (abandon x11 about, via seed-to-master) returns an address (that address is shown).
  detect: filled by crates/blocktools/tests/chain_caps.rs, which runs address::detect on the shown
          address; this script copies the column through and the test fails if it is wrong.
  sign:   the signing route accepts the chain past its chain check: tx-build (UTXO; replies
          "--utxos FILE required"), tx-verify on an unsigned EVM tx (reaches fee_above_cap under that chain),
          acct-tx build (reaches a missing-flag error; for --chain atom a full build with a
          mismatched pubkey must get past the hrp check to pubkey_does_not_match_from), xrp-tx build, sol-tron-tx build. "no" = every route refused it.
'sign' says a signer accepts the chain, not that its output is independently verified: see the
sources and vector notes in the text (e.g. 20 Cosmos hrps + evmos are signed with vectors
generated by running Trust Wallet Core, not independent ones)."""
import json, os, re, subprocess, sys
args = [a for a in sys.argv[1:] if a != "--check"]
check = "--check" in sys.argv
B = args[0] if args else os.environ.get("BIN", "target/release")  # BIN: as gen-man.py (gate-negatives exports it)
PHRASE = " ".join(["abandon"] * 11 + ["about"])
BEGIN, END = "<!-- chain-caps:begin -->", "<!-- chain-caps:end -->"
def run(cmd, inp=""):
    p = subprocess.run([os.path.join(B, cmd[0])] + cmd[1:], input=inp, capture_output=True, text=True, timeout=60)
    return p.stdout + p.stderr
master = run(["seed-to-master"], PHRASE + "\n")
EVM = open("crates/blocktools/tests/data/evm-fee-9.99eth.txt").read().strip()
G = "0279be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798"  # secp256k1 generator: never the test-phrase key
ACCT = {"xlm", "algo", "ton", "ada", "dot"}
def sign(c, addr):
    if "--utxos FILE required" in run(["tx-build", "--chain", c]): return "tx-build"
    o = run(["tx-verify", "--chain", c, "--chain-id", "1", "--expect-to", "0x" + "35" * 20], EVM)
    if "fee_above_cap" in o and f'"chain":"{c}"' in o: return "tx-sign"  # tx-verify reads EVM by format; the fee cap names the chain
    if c in ACCT and "unsupported" not in (o := run(["acct-tx", "build", "--chain", c])) and "usage" not in o: return "acct-tx"
    if c == "xrp" and "missing --account" in run(["xrp-tx", "build"]): return "xrp-tx"
    if c in ("sol", "tron") and "build_needs_--plan" in run(["sol-tron-tx", "build", "--chain", c]): return "sol-tron-tx"
    if addr:  # Cosmos: the hrp check comes first; a vectorless hrp is refused (cosmos_hrp_without_vector)
        o = run(["acct-tx", "build", "--chain", "atom", "--from", addr, "--pubkey", G, "--to", addr, "--amount", "1", "--fee", "1",
                 "--gas", "1", "--sequence", "0", "--account-number", "0"])
        if "pubkey_does_not_match_from" in o: return "acct-tx"
    return "no"
rows = [json.loads(l) for l in run(["chain-table"]).splitlines() if l.strip()]
doc = open("docs/CHAINS.md").read()
old = {}
if BEGIN in doc:
    for l in doc.split(BEGIN)[1].split(END)[0].splitlines():
        f = [x.strip() for x in l.strip().strip("|").split("|")]
        if len(f) == 5 and f[0] not in ("chain", "---"): old[f[0]] = f[2]
out = ["| chain | derive | detect | sign | address from the test phrase |", "|---|---|---|---|---|"]
for r in rows:
    c = r["name"]
    a = next((json.loads(l).get("address") for l in run(["derive", "--chain", c, "--count", "1", "--public-only"], master).splitlines() if '"address"' in l), None)
    out.append(f"| {c} | {'yes' if a else 'no'} | {old.get(c, '?') if a else '—'} | {sign(c, a)} | {('`' + a + '`') if a else '—'} |")
table = "\n".join(out)
if not check: print(table); sys.exit(0)
if BEGIN not in doc: sys.exit("chain-caps: docs/CHAINS.md has no chain-caps table")
cur = doc.split(BEGIN)[1].split(END)[0].strip()
def strip_detect(t): return [re.sub(r"^(\|[^|]*\|[^|]*\|)[^|]*\|", r"\1|", l) for l in t.splitlines()]
if strip_detect(cur) != strip_detect(table):
    for a, b in zip(strip_detect(cur), strip_detect(table)):
        if a != b: print(f"  doc:      {a}\n  measured: {b}", file=sys.stderr)
    sys.exit("chain-caps: docs/CHAINS.md chain-caps table differs from what the CLIs do (python3 scripts/chain-caps.py)")
print(f"chain-caps ok ({len(rows)} rows)")

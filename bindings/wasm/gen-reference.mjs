// Generate docs/EXPORTS-reference.md from what the wasm package actually does.
//   node gen-reference.mjs          write the reference
//   node gen-reference.mjs --check  fail if the committed reference differs (run by scripts/wasm-check.sh)
// Every example is a real call recorded while bindings/wasm/test.mjs runs against public vectors, replayed
// here with full arguments; outputs longer than 600 chars are cut and marked. Needs pkg/node (wasm-check.sh).
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const bt = createRequire(import.meta.url)('./pkg/node/blocktools_wasm.js');
const DOC = new URL('../../docs/EXPORTS-reference.md', here);
const names = Object.keys(bt).filter(k => typeof bt[k] === 'function' && !/^__|^init/.test(k)).sort();
const log = {};
const lit = a => a instanceof Uint32Array ? `new Uint32Array(${JSON.stringify([...a])})` : JSON.stringify(a);
for (const k of names) {
  const f = bt[k];
  bt[k] = (...a) => {
    const e = (log[k] ??= { calls: 0, ok: null, err: null }); e.calls++;
    const src = `${k}(${a.map(lit).join(', ')})`;
    try { const r = f(...a); if (!e.ok || src.length < e.ok.src.length) e.ok = { src, out: r }; return r; }
    catch (x) { const m = String(x.message ?? x); if (!e.err || src.length < e.err.src.length) e.err = { src, out: m }; throw x; }
  };
}
const quiet = console.log; console.log = () => {};
await import(new URL('./test.mjs', import.meta.url));
console.log = quiet;
for (const k of names) bt[k] = createRequire(import.meta.url)('./pkg/node/blocktools_wasm.js')[k];
// signatures + doc comments from the generated .d.ts
const dts = readFileSync(new URL('./pkg/node/blocktools_wasm.d.ts', here), 'utf8');
const sig = {};
for (const m of dts.matchAll(/(?:\/\*\*([\s\S]*?)\*\/\s*)?export function (\w+)\(([^)]*)\): ([^;]+);/g))
  sig[m[2]] = { doc: (m[1] || '').split('\n').map(l => l.replace(/^\s*\* ?/, '')).join(' ').replace(/\s+/g, ' ').trim(), args: m[3], ret: m[4] };
const cut = (s, n = 600) => s.length > n ? s.slice(0, n) + ` … [cut: ${s.length} chars total]` : s;
const L = [];
L.push('# wasm export reference (generated)', '',
  'Generated by `node bindings/wasm/gen-reference.mjs` from the built package; `scripts/wasm-check.sh` fails if this file is stale.',
  'Do not edit by hand. Every example below was executed: it is a call `bindings/wasm/test.mjs` makes against public',
  'test vectors, replayed by the generator. Outputs over 600 characters are cut and marked. Measured on Linux x86_64',
  '(Node); macOS and browsers are untested by this generator (test-web.mjs runs the web build under Node only).', '',
  'The stable subset and its guarantees are in [../EXPORTS.md](../EXPORTS.md). This file covers every export, including legacy ones.', '',
  'Conventions (from the code): functions return strings, usually JSON text, so `JSON.parse` the result. Failures throw a JS',
  '`Error` whose message is a short code such as `bad_hex` or `bad_json`. `checkTx` never throws: it returns `{"ok":false,"reasons":[...]}`.',
  'The package has no private-key code (enforced by wasm-check.sh): nothing here signs.', '',
  `Exports: ${names.length}. Exports never called by test.mjs have no example and are listed as untested.`, '');
for (const k of names) {
  const s = sig[k] || { doc: '', args: '?', ret: '?' }; const e = log[k];
  L.push(`## \`${k}\``, '', '```ts', `${k}(${s.args}): ${s.ret}`, '```', '');
  if (s.doc) L.push(s.doc, '');
  if (!e) { L.push('**Untested:** test.mjs never calls this export.', ''); continue; }
  L.push(`Calls in test.mjs: ${e.calls}.`, '');
  if (e.ok) L.push('Example (executed):', '', '```js', `bt.${e.ok.src}`, `// -> ${cut(e.ok.out)}`, '```', '');
  if (e.err) L.push('Error example (executed):', '', '```js', `bt.${e.err.src}`, `// throws ${e.err.out}`, '```', '');
}
const text = L.join('\n');
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(DOC, 'utf8'); } catch {}
  if (cur !== text) { console.log('FAIL docs/EXPORTS-reference.md is stale: run node bindings/wasm/gen-reference.mjs'); process.exit(1); }
  console.log('exports-reference ok'); process.exit(0);
}
writeFileSync(DOC, text);
console.log(`wrote docs/EXPORTS-reference.md (${names.length} exports, ${names.filter(k => log[k]).length} with examples)`);
